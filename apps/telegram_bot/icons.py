"""Премиум-эмодзи для кнопок бота: идентификаторы и запасные символы.

Своего набора у нас нет — идентификаторы взяты из открытых наборов Telegram
(`tgiosicons`, `UnigramIcons`, `Vector Icons`). У каждой иконки записано, из
какого набора она пришла: наборы различаются рисовкой, и смешение видно только
глазами в живом клиенте, поэтому источник должен быть виден в коде.

Где это применимо и где нет:

* `InlineKeyboardButton(icon_custom_emoji_id=...)` — иконка кнопки. Работает
  только у бота, владелец которого держит Telegram Premium. Проверить статус
  владельца из кода нельзя, поэтому иконки закрыты флагом
  ``TELEGRAM_BUTTON_ICONS_ENABLED`` и по умолчанию выключены: включённые без
  Premium, они сломали бы каждую клавиатуру, а выключенные не ломают ничего.
* Тело сообщения — **нельзя**. Сущность `custom_emoji` в тексте Bot API
  разрешает только ботам, купившим дополнительное имя на Fragment; у нас его
  нет, и такое сообщение ушло бы в ошибку целиком, а не деградировало до
  запасного символа. Поэтому хелпера для текста здесь нет вовсе.

Запасной символ обязателен у каждой иконки: он показывается, когда флаг
выключен, и подставляется клиентом вместо непрогрузившейся иконки. Заменять его
на обычный знак (`+`, `✓`) нельзя — Bot API требует, чтобы сущность
`custom_emoji` покрывала ровно один эмодзи, а `✓` (U+2713) эмодзи не является,
хотя и лежит в блоке Dingbats рядом с настоящими. Поэтому проверка ниже — не
диапазон, а порог плюс поимённо разобранный список исключений.
"""

from __future__ import annotations


TGIOS = 'tgiosicons'
UNIGRAM = 'UnigramIcons'
VECTOR = 'SdmFH9KUAGAAAJCCCACF_by_e4zybot'

# Эмодзи ниже U+1F300 лежат вперемешку с обычными знаками, поэтому каждый такой
# запасной символ разбирается поимённо. Добавление иконки с новым символом из
# старых блоков обязано пройти через этот список — это и есть проверка.
LEGACY_BLOCK_EMOJI = frozenset('✅❌')

# Модификаторы последовательностей эмодзи: селектор представления, склейка и
# рамка клавиши. Записаны кодами — в исходнике они невидимы.
EMOJI_MODIFIERS = frozenset('\ufe0f\u200d\u20e3')


class Icon(str):
    """Идентификатор премиум-эмодзи, знающий свой запасной символ и набор.

    Наследник `str`, а не отдельный тип: значение уходит в поле Bot API как
    обычная строка, поэтому ни один вызов от появления класса не меняется.
    """

    fallback: str
    set_name: str

    def __new__(cls, emoji_id: str, fallback: str, set_name: str) -> 'Icon':
        icon = super().__new__(cls, emoji_id)
        icon.fallback = fallback
        icon.set_name = set_name
        return icon


def is_emoji(symbol: str) -> bool:
    """Проверить, что строка целиком состоит из эмодзи, а не из похожих знаков."""
    if not symbol:
        return False

    return all(
        character in EMOJI_MODIFIERS or character in LEGACY_BLOCK_EMOJI or ord(character) >= 0x1F300
        for character in symbol
    )


