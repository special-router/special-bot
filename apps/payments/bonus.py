"""Объёмный бонус к пополнению — одна лестница на все способы оплаты.

Лестница жила внутри обработчика карточного платежа, и пока карта была
единственным способом, копии не существовало. С появлением криптовалюты вторая
копия означала бы, что за одни и те же деньги клиент получает разный баланс в
зависимости от способа оплаты, — расхождение, которое никто не заметил бы до
первой жалобы. Поэтому сумма к зачислению считается здесь, а обработчики только
передают уплаченное.
"""
from __future__ import annotations

from decimal import Decimal


# Порог и надбавка. Порядок — от большего порога к меньшему: применяется первый
# сработавший, как в исходном каскаде if/elif.
_LADDER: tuple[tuple[Decimal, Decimal], ...] = (
    (Decimal('2520'), Decimal('0.3')),
    (Decimal('1250'), Decimal('0.2')),
    (Decimal('600'), Decimal('0.1')),
    (Decimal('400'), Decimal('0.05')),
)


def topup_bonus_amount(paid_rub) -> Decimal:
    """Сколько зачислить на баланс за уплаченные ``paid_rub`` рублей.

    Ниже первого порога зачисляется ровно уплаченное. Выше — сумма с надбавкой,
    усечённая до рубля, как и было в карточном обработчике: баланс списывается
    сутками по целым рублям, и копейка бонуса ни на что не влияет.
    """
    amount = paid_rub if isinstance(paid_rub, Decimal) else Decimal(str(paid_rub))
    for threshold, percent in _LADDER:
        if amount > threshold:
            return Decimal(int(amount + amount * percent))
    return amount
